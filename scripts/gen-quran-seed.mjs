// Generates the Qur'an reference data from quran-meta (MIT, pinned in package.json):
//   src/quran/data.generated.ts  — compact tables for the app
//   supabase/seed_quran.sql      — quran_surahs + quran_ayahs for the database
// Run: npm run gen:quran
import fs from 'node:fs';
import { getList, getAyahMeta, getSurahMeta } from 'quran-meta/hafs';

const EN = JSON.parse(fs.readFileSync(new URL('./surah-names-en.json', import.meta.url)));
const surahs = [];
for (let s = 1; s <= 114; s++) {
  const m = getSurahMeta(s);
  surahs.push({ n: s, en: EN[s - 1], ar: m.name, count: m.ayahCount, first: m.firstAyahId, meccan: m.isMeccan });
}
const TOTAL = surahs.reduce((a, s) => a + s.count, 0);
if (TOTAL !== 6236) throw new Error('ayah total ' + TOTAL);
const ayahs = [];
for (let id = 1; id <= TOTAL; id++) {
  const m = getAyahMeta(id);
  ayahs.push({ id, s: m.surah, a: m.ayah, page: m.page, juz: m.juz, hizb: m.hizbId, rub: m.rubAlHizbId });
}
const starts = key => { const out = []; let prev = 0; for (const x of ayahs) if (x[key] !== prev) { out.push(x.id); prev = x[key]; } return out; };
const pageStarts = starts('page'), juzStarts = starts('juz'), rubStarts = starts('rub');
if (pageStarts.length !== 604 || juzStarts.length !== 30 || rubStarts.length !== 240) throw new Error('structure counts');
// sanity checks against well-known Madinah mushaf facts
const at = (s, a) => ayahs.find(x => x.s === s && x.a === a);
const expect = (c, msg) => { if (!c) throw new Error('check failed: ' + msg); };
expect(at(67, 1).page === 562 && at(67, 1).juz === 29, 'Al-Mulk 1 = page 562, juz 29');
expect(at(78, 1).page === 582 && at(78, 1).juz === 30, 'An-Naba 1 = page 582, juz 30');
expect(at(2, 142).juz === 2 && at(2, 1).page === 2, 'Juz 2 starts 2:142');
expect(at(114, 6).page === 604, 'An-Nas ends on page 604');

const ts = `// GENERATED by scripts/gen-quran-seed.mjs from quran-meta 6.0.17 (MIT, Hafs, Madinah 604-page numbering). Do not edit.
export const SOURCE = { name: 'quran-meta', version: '6.0.17', license: 'MIT', riwayah: 'Hafs an Asim', mushaf: 'Madinah 15-line, 604 pages' } as const;
export const TOTAL_AYAHS = ${TOTAL};
/** [english name, arabic name, ayah count, first global ayah id, meccan] */
export const SURAHS: ReadonlyArray<readonly [string, string, number, number, boolean]> = ${JSON.stringify(surahs.map(s => [s.en, s.ar, s.count, s.first, s.meccan]))};
/** first global ayah id of each page 1..604 */
export const PAGE_STARTS: readonly number[] = ${JSON.stringify(pageStarts)};
/** first global ayah id of each juz 1..30 */
export const JUZ_STARTS: readonly number[] = ${JSON.stringify(juzStarts)};
/** first global ayah id of each rub' al-hizb 1..240 (hizb = ceil(rub / 4)) */
export const RUB_STARTS: readonly number[] = ${JSON.stringify(rubStarts)};
`;
fs.writeFileSync(new URL('../src/quran/data.generated.ts', import.meta.url), ts);

const q = s => `'${String(s).replace(/'/g, "''")}'`;
let sql = `-- GENERATED by scripts/gen-quran-seed.mjs from quran-meta 6.0.17 (MIT). Hafs, Madinah 604-page numbering.\n`;
sql += `insert into public.quran_surahs (number, name_en, name_ar, ayah_count, first_ayah_id) values\n`;
sql += surahs.map(s => `(${s.n}, ${q(s.en)}, ${q(s.ar)}, ${s.count}, ${s.first})`).join(',\n') + '\non conflict (number) do nothing;\n';
sql += `insert into public.quran_ayahs (id, surah, ayah, page, juz, hizb, rub) values\n`;
sql += ayahs.map(x => `(${x.id},${x.s},${x.a},${x.page},${x.juz},${x.hizb},${x.rub})`).join(',\n') + '\non conflict (id) do nothing;\n';
fs.writeFileSync(new URL('../supabase/seed_quran.sql', import.meta.url), sql);
console.log('ok', TOTAL, 'ayahs,', pageStarts.length, 'pages,', juzStarts.length, 'juz,', rubStarts.length, 'rub');
