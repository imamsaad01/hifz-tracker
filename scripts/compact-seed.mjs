// Writes supabase/seed_quran_compact.sql: the same rows as seed_quran.sql, generated in SQL from boundary arrays (13 KB instead of 174 KB).
import fs from 'node:fs';
const src = fs.readFileSync('src/quran/data.generated.ts', 'utf8');
const grab = n => JSON.parse(src.match(new RegExp(`export const ${n}[^=]*= (\\[.*?\\]);`, 's'))[1]);
const SURAHS = grab('SURAHS'), PAGE = grab('PAGE_STARTS'), JUZ = grab('JUZ_STARTS'), RUB = grab('RUB_STARTS');
const q = s => `'${s.replace(/'/g, "''")}'`;
let out = `-- GENERATED by scripts/compact-seed.mjs from quran-meta 6.0.17 (MIT): Hafs, Madinah 604-page numbering.\n`;
out += `insert into public.quran_surahs (number, name_en, name_ar, ayah_count, first_ayah_id) values\n${SURAHS.map((s, i) => `(${i + 1},${q(s[0])},${q(s[1])},${s[2]},${s[3]})`).join(',\n')}\non conflict (number) do nothing;\n`;
out += `with b as (select array[${PAGE.join(',')}]::int[] p, array[${JUZ.join(',')}]::int[] j, array[${RUB.join(',')}]::int[] r),
ay as (select s.number as surah, g.n as ayah, s.first_ayah_id + g.n - 1 as id from public.quran_surahs s cross join lateral generate_series(1, s.ayah_count) g(n))
insert into public.quran_ayahs (id, surah, ayah, page, juz, hizb, rub)
select ay.id, ay.surah, ay.ayah,
  (select count(*) from unnest(b.p) x where x <= ay.id),
  (select count(*) from unnest(b.j) x where x <= ay.id),
  ((select count(*) from unnest(b.r) x where x <= ay.id) + 3) / 4,
  (select count(*) from unnest(b.r) x where x <= ay.id)
from ay, b on conflict (id) do nothing;\n`;
fs.writeFileSync('supabase/seed_quran_compact.sql', out);
console.log(out.length, PAGE.length, JUZ.length, RUB.length);
